import { useState } from "react";
import { Screen, Panel, Table, Status, Field, Select, Button, Details } from "@/components/manager/ManagerUI";
import { AsyncBoundary, TruncatedNotice, ConfirmDialog } from "@/components/bom/LiveBomUI";
import { Kpis } from "@/components/bom/BomUI";
import { CellDialog, RackDialog, ZoneDialog } from "@/components/bom/WarehouseStructureDialogs";
import { ManagedCapacityDialog } from "@/components/bom/ManagedCapacityDialog";
import { useAsyncData } from "@/lib/useAsyncData";
import { loadCells, loadFacilities, loadManagedCapacity, loadRacks, loadZones } from "@/lib/bomApiData";
import { bomWarehouseApi } from "@/api/bomApi";
import { countBy, formatKg as kg, formatM3 as m3, sumBy } from "@/lib/bomMetrics";

// Warehouse structure console shared by BOM and Admin (ADMIN and BOM are both listed in the
// backend `managers` role set for warehouse-map writes).
// IMPORTANT backend rule: every zone/rack/cell read and write validates the facility through
// facilityForMap, which requires status ACTIVE + serviceTypes MANAGED_INVENTORY. Facilities
// that do not qualify answer 409, so the selector only offers eligible facilities.
const eligible = (facility) => facility.status === "ACTIVE" && facility.serviceTypes.includes("MANAGED_INVENTORY");
const dims = (d) => `${d.widthM}×${d.depthM}×${d.heightM} m`;

// The capacity read is interval based, so the console reports on the current calendar month.
function currentMonthWindow() {
  const now = new Date();
  const start = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1));
  const end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 0, 23, 59, 59));
  return { startDate: start.toISOString(), endDate: end.toISOString() };
}

export default function WarehouseStructurePage() {
  const directory = useAsyncData(loadFacilities, []);
  const [facilityId, setFacilityId] = useState("");
  const [zoneFilter, setZoneFilter] = useState("");
  const [rackId, setRackId] = useState("");
  const [zoneDialog, setZoneDialog] = useState(null);
  const [rackDialog, setRackDialog] = useState(null);
  const [cellDialog, setCellDialog] = useState(null);
  const [capacityOpen, setCapacityOpen] = useState(false);
  const [confirm, setConfirm] = useState(null);
  const window = currentMonthWindow();

  const zones = useAsyncData(({ signal }) => (facilityId ? loadZones(facilityId, { signal }) : Promise.resolve(null)), [facilityId]);
  const racks = useAsyncData(({ signal }) => (facilityId ? loadRacks(facilityId, { signal }) : Promise.resolve(null)), [facilityId]);
  const cells = useAsyncData(
    ({ signal }) => (facilityId && rackId ? loadCells(facilityId, rackId, { signal }) : Promise.resolve(null)),
    [facilityId, rackId],
  );
  const capacity = useAsyncData(
    ({ signal }) => (facilityId ? loadManagedCapacity(facilityId, { ...window, signal }) : Promise.resolve(null)),
    [facilityId],
  );

  function selectFacility(id) {
    setFacilityId(id);
    setZoneFilter("");
    setRackId("");
  }

  function reloadStructure() {
    zones.reload();
    racks.reload();
    if (rackId) cells.reload();
  }
  function removeZone(zone) {
    setConfirm({
      title: `Delete zone ${zone.code}?`,
      summary: "A zone can only be deleted after all of its racks are deleted. Deleted rows are hidden from every list, so the console cannot restore them afterwards.",
      label: "Delete zone",
      run: async () => { await bomWarehouseApi.deleteZone(zone.id); reloadStructure(); },
    });
  }

  function removeRack(rack) {
    setConfirm({
      title: `Delete rack ${rack.rackCode}?`,
      summary: "A rack can only be deleted once every cell is BLOCKED or under MAINTENANCE, and no cell holds inventory, holds or bookings.",
      label: "Delete rack",
      run: async () => { await bomWarehouseApi.deleteRack(rack.id); if (rack.id === rackId) setRackId(""); reloadStructure(); },
    });
  }

  return (
    <Screen
      title="Warehouse structure"
      description="Zones, racks and rack cells of a Managed Inventory facility. Zones and racks are fully editable; cells accept limited updates."
    >
      <AsyncBoundary state={directory} render={(facilities) => {
        const options = facilities.filter(eligible);
        const excluded = facilities.length - options.length;
        return (
          <>
            <Kpis items={[
              ["Facilities shown", options.length, "ACTIVE and offering MANAGED_INVENTORY"],
              ["Zones", zones.data?.total ?? "—", "Zones in the selected facility"],
              ["Racks", racks.data?.total ?? "—", "Racks in the selected facility"],
              ["Cells", sumBy(racks.data?.rows || [], "cellCount") || "—", "Generated by the backend per rack"],
            ]} />

            <Panel
              title="Structure scope"
              subtitle="The warehouse map validates the facility on every read and write, so only ACTIVE facilities that offer Managed Inventory are listed."
            >
              <div className="manager-filters">
                <Field label="Facility">
                  <Select
                    label="Warehouse facility"
                    value={facilityId}
                    onChange={selectFacility}
                    options={[["", "Select a facility"], ...options.map((f) => [f.id, `${f.name} (${f.code})`])]}
                  />
                </Field>
                <Field label="Zone filter" hint="Narrows the rack list only.">
                  <Select
                    label="Zone filter"
                    value={zoneFilter}
                    onChange={setZoneFilter}
                    disabled={!facilityId}
                    options={[["", "All zones"], ...(zones.data?.rows || []).map((z) => [z.id, `${z.code} · ${z.name}`])]}
                  />
                </Field>
              </div>
              {excluded > 0 && (
                <p className="bom-warning mt-5">
                  {excluded} other facilit{excluded === 1 ? "y is" : "ies are"} hidden: the warehouse map rejects a facility that is not
                  ACTIVE or does not offer Managed Inventory with 409.
                </p>
              )}
            </Panel>

            {!facilityId && (
              <Panel title="Select a facility">
                <p className="text-sm text-slate-500">Zones, racks and cells are scoped to one facility.</p>
              </Panel>
            )}

            {facilityId && (
              <>
                <Panel
                  title="Managed capacity"
                  subtitle="Sellable quota the managed reservation flow can allocate, measured over the current calendar month."
                  action={<Button onClick={() => setCapacityOpen(true)}>Configure capacity</Button>}
                >
                  <AsyncBoundary state={capacity} render={(data) => (data ? (
                    <Details values={[
                      ["Interval", `${String(data.interval?.startDate || window.startDate).slice(0, 10)} → ${String(data.interval?.endDate || window.endDate).slice(0, 10)}`],
                      ["Sellable capacity", m3(data.sellableCapacityM3)],
                      ["Committed peak", m3(data.committedPeakCapacityM3)],
                      ["Available", m3(data.availableCapacityM3)],
                      ["Overdue obligation", m3(data.unresolvedOverdueObligationM3)],
                    ]} />
                  ) : (
                    <p className="bom-warning">
                      No active capacity configuration. The read endpoint answers 404 until a quota row exists for this facility, so
                      Managed reservations cannot be created yet. Use Configure capacity to set sellableCapacityM3 and holdDurationMinutes.
                    </p>
                  ))} />
                </Panel>

                <AsyncBoundary state={zones} render={(data) => (data ? (
                  <Panel
                    title="Zones"
                    subtitle={`${data.total} zone${data.total === 1 ? "" : "s"} · zones order the warehouse into logical areas`}
                    action={<Button onClick={() => setZoneDialog("new")}>Create zone</Button>}
                  >
                    {data.truncated && <TruncatedNotice total={data.total} shown={data.rows.length} />}
                    <Table
                      label="Warehouse zones"
                      rows={data.rows}
                      columns={[
                        { key: "code", label: "Code" },
                        { key: "name", label: "Name" },
                        { key: "sortOrder", label: "Sort order" },
                        { key: "state", label: "State", render: (r) => <Status value={r.isActive ? "ACTIVE" : "INACTIVE"} /> },
                        { key: "description", label: "Description", render: (r) => r.description || "—" },
                        {
                          key: "actions",
                          label: "Actions",
                          render: (r) => (
                            <div className="flex flex-wrap gap-2">
                              <Button size="sm" variant="outline" onClick={() => setZoneDialog(r)}>Edit</Button>
                              <Button size="sm" variant="outline" onClick={() => removeZone(r)}>Delete</Button>
                            </div>
                          ),
                        },
                      ]}
                      empty="No warehouse zone is configured for this facility."
                    />
                  </Panel>
                ) : null)} />

                <AsyncBoundary state={racks} render={(data) => (data ? (
                  <Panel
                    title="Racks"
                    subtitle="Racks carry the physical dimensions, the level rating and the map position used by the customer map."
                    action={(
                      <Button onClick={() => setRackDialog("new")} disabled={!(zones.data?.rows || []).length}>
                        Create rack
                      </Button>
                    )}
                  >
                    {data.truncated && <TruncatedNotice total={data.total} shown={data.rows.length} />}
                    {!(zones.data?.rows || []).length && (
                      <p className="bom-warning mb-4">Create an active zone before adding racks.</p>
                    )}
                    <Table
                      label="Warehouse racks"
                      rows={data.rows.filter((rack) => !zoneFilter || rack.zoneId === zoneFilter)}
                      columns={[
                        { key: "rackCode", label: "Rack" },
                        { key: "zone", label: "Zone", render: (r) => (zones.data?.rows || []).find((z) => z.id === r.zoneId)?.code || "—" },
                        { key: "aisleCode", label: "Aisle" },
                        { key: "operationalStatus", label: "Status", render: (r) => <Status value={r.operationalStatus} /> },
                        { key: "layout", label: "Layout", render: (r) => `${r.levelCount} levels × ${r.cellsPerLevel} cells (${r.cellCount})` },
                        { key: "dimensions", label: "Dimensions", render: (r) => dims(r.dimensions) },
                        { key: "maxWeightKg", label: "Rated weight", render: (r) => `${kg(r.maxWeightKg)} · ${kg(r.maxWeightKgPerLevel)}/level` },
                        { key: "map", label: "Map", render: (r) => `X ${r.mapX} · Y ${r.mapY} · ${r.orientation}°` },
                        {
                          key: "actions",
                          label: "Actions",
                          render: (r) => (
                            <div className="flex flex-wrap gap-2">
                              <Button size="sm" variant="outline" onClick={() => setRackId(r.id)}>Cells</Button>
                              <Button size="sm" variant="outline" onClick={() => setRackDialog(r)}>Edit</Button>
                              <Button size="sm" variant="outline" onClick={() => removeRack(r)}>Delete</Button>
                            </div>
                          ),
                        },
                      ]}
                      empty="No rack is registered in this facility (or the selected zone)."
                    />
                  </Panel>
                ) : null)} />

                {rackId && (
                  <AsyncBoundary state={cells} render={(data) => (data ? (
                    <Panel
                      title="Rack cells"
                      subtitle={`${data.total} cell${data.total === 1 ? "" : "s"} · cells are generated with the rack and only accept a limited patch`}
                      action={<Button variant="outline" onClick={() => setRackId("")}>Close cells</Button>}
                    >
                      <Details values={[
                        ["Rack", (racks.data?.rows || []).find((r) => r.id === rackId)?.rackCode || rackId],
                        ["Available cells", countBy(data.rows, "operationalStatus", "AVAILABLE")],
                        ["Rated cell weight", kg(sumBy(data.rows, "maxWeightKg"))],
                        ["Cell volume", m3(sumBy(data.rows, "usableVolumeM3"))],
                      ]} />
                      <div className="mt-5">
                        <Table
                          label="Rack cells"
                          rows={data.rows}
                          columns={[
                            { key: "code", label: "Cell" },
                            { key: "levelNumber", label: "Level" },
                            { key: "cellNumber", label: "Position" },
                            { key: "dimensions", label: "Dimensions", render: (r) => `${r.dimensions.widthM}×${r.dimensions.depthM} m · ${r.dimensions.usableHeightM ?? "—"} m usable` },
                            { key: "maxWeightKg", label: "Max weight", render: (r) => kg(r.maxWeightKg) },
                            { key: "usableVolumeM3", label: "Volume", render: (r) => (r.usableVolumeM3 === null ? "—" : m3(r.usableVolumeM3)) },
                            { key: "operationalStatus", label: "Status", render: (r) => <Status value={r.operationalStatus} /> },
                            {
                              key: "actions",
                              label: "Actions",
                              render: (r) => <Button size="sm" variant="outline" onClick={() => setCellDialog(r)}>Edit</Button>,
                            },
                          ]}
                          empty="This rack has no cells."
                        />
                      </div>
                    </Panel>
                  ) : null)} />
                )}
              </>
            )}
          </>
        );
      }} />

      {zoneDialog && (
        <ZoneDialog
          facilityId={facilityId}
          zone={zoneDialog === "new" ? null : zoneDialog}
          onClose={() => setZoneDialog(null)}
          onSaved={reloadStructure}
        />
      )}
      {rackDialog && (
        <RackDialog
          facilityId={facilityId}
          zones={(zones.data?.rows || []).filter((z) => z.isActive)}
          rack={rackDialog === "new" ? null : rackDialog}
          onClose={() => setRackDialog(null)}
          onSaved={reloadStructure}
        />
      )}
      {cellDialog && (
        <CellDialog cell={cellDialog} onClose={() => setCellDialog(null)} onSaved={() => cells.reload()} />
      )}
      {capacityOpen && (
        <ManagedCapacityDialog
          facilityId={facilityId}
          facilityLabel={(directory.data || []).find((f) => f.id === facilityId)?.name || facilityId}
          configured={Boolean(capacity.data)}
          onClose={() => setCapacityOpen(false)}
          onSaved={capacity.reload}
        />
      )}
      {confirm && (
        <ConfirmDialog
          title={confirm.title}
          summary={<p className="text-sm text-slate-500">{confirm.summary}</p>}
          confirmLabel={confirm.label}
          onConfirm={confirm.run}
          onClose={() => setConfirm(null)}
        />
      )}
    </Screen>
  );
}
