import { useState } from "react";
import { Dialog, Button, Field, Input, Select, Message } from "@/components/manager/ManagerUI";
import { bomWarehouseApi } from "@/api/bomApi";
import { apiErrorMessage } from "@/lib/apiError";

// Write dialogs for the warehouse structure console.
// The forms mirror the backend validation exactly (warehouse-map.validation.ts):
//   zone  create {facilityId, code, name, description?, color?, sortOrder?, isActive?}
//   rack  create {facilityId, zoneId, aisleCode, rackCode, dimensions, levelCount, cellsPerLevel,
//                 maxWeightKgPerLevel, mapX, mapY, orientation, operationalStatus, cellCapacitiesKg?}
//   cell  patch  {maxWeightKg?, dimensions{usableHeightM?}, operationalStatus?}
// Rack cells are generated by the backend when a rack is created, so the console tunes each
// cell afterwards instead of offering a cell create route (the backend has none).

export const OPERATIONAL_STATUSES = [["AVAILABLE", "Available"], ["BLOCKED", "Blocked"], ["MAINTENANCE", "Maintenance"]];
export const ORIENTATIONS = [["0", "0° north"], ["90", "90° east"], ["180", "180° south"], ["270", "270° west"]];
const ACTIVE_OPTIONS = [["true", "Active"], ["false", "Inactive"]];
const CODE_PATTERN = /^[a-zA-Z0-9][a-zA-Z0-9_-]*$/;

const number = (value) => (String(value).trim() ? Number(value) : NaN);
const isPositive = (value, max = 10000) => Number.isFinite(number(value)) && number(value) > 0 && number(value) <= max;
const isInteger = (value, min, max) => Number.isSafeInteger(number(value)) && number(value) >= min && number(value) <= max;
const filled = (value) => String(value).trim() !== "";
// Float safe split that can never round above the level rating the backend validates against.
const floor2 = (value) => Math.floor(value * 100) / 100;

function Form({ pending, error, onClose, onSubmit, children, submitLabel }) {
  return (
    <form className="space-y-5" onSubmit={onSubmit}>
      {children}
      <Message error={error} />
      <div className="flex flex-wrap gap-3">
        <Button type="submit" variant="orange" disabled={pending}>{pending ? "Saving…" : submitLabel}</Button>
        <Button type="button" variant="outline" disabled={pending} onClick={onClose}>Cancel</Button>
      </div>
    </form>
  );
}

/* ------------------------------- Zone ------------------------------- */
export function ZoneDialog({ facilityId, zone, onClose, onSaved }) {
  const editing = Boolean(zone);
  const [form, setForm] = useState({
    code: zone?.code || "",
    name: zone?.name || "",
    description: zone?.description || "",
    color: zone?.color || "",
    sortOrder: String(zone?.sortOrder ?? 0),
    isActive: zone ? String(zone.isActive) : "true",
  });
  const [pending, setPending] = useState(false);
  const [error, setError] = useState("");
  const change = (key, value) => setForm((f) => ({ ...f, [key]: value }));

  async function submit(event) {
    event.preventDefault();
    if (pending) return;
    setError("");
    const code = form.code.trim().toUpperCase();
    if (!editing && (!code || code.length > 40 || !CODE_PATTERN.test(code))) {
      setError("Zone code must be 1-40 characters: letters, digits, underscore or hyphen, starting with a letter or digit.");
      return;
    }
    if (!form.name.trim() || form.name.trim().length > 120) {
      setError("Zone name is required and must be at most 120 characters.");
      return;
    }
    if (form.description.trim().length > 1000) {
      setError("Description must be at most 1000 characters.");
      return;
    }
    if (filled(form.color) && !/^#[0-9a-fA-F]{6}$/.test(form.color.trim())) {
      setError("Colour must be a six-digit hex value such as #2F855A.");
      return;
    }
    if (!isInteger(form.sortOrder, 0, 100000)) {
      setError("Sort order must be a whole number from 0 to 100000.");
      return;
    }
    setPending(true);
    try {
      const body = {
        name: form.name.trim(),
        sortOrder: number(form.sortOrder),
        isActive: form.isActive === "true",
      };
      if (!editing) {
        body.facilityId = facilityId;
        body.code = code;
      }
      if (filled(form.description)) body.description = form.description.trim();
      if (filled(form.color)) body.color = form.color.trim().toUpperCase();
      if (editing) await bomWarehouseApi.updateZone(zone.id, body);
      else await bomWarehouseApi.createZone(body);
      onSaved?.();
      onClose?.();
    } catch (err) {
      setError(apiErrorMessage(err));
    } finally {
      setPending(false);
    }
  }

  return (
    <Dialog title={editing ? `Edit zone ${zone.code}` : "Create warehouse zone"} onClose={onClose}>
      <Form pending={pending} error={error} onClose={onClose} onSubmit={submit} submitLabel={editing ? "Save zone" : "Create zone"}>
        <div className="manager-filters">
          {!editing && (
            <Field label="Zone code" hint="Uppercased; unique per facility.">
              <Input aria-label="Zone code" required value={form.code} onChange={(e) => change("code", e.target.value)} />
            </Field>
          )}
          <Field label="Zone name">
            <Input aria-label="Zone name" required value={form.name} onChange={(e) => change("name", e.target.value)} />
          </Field>
          <Field label="Sort order" hint="Zones are listed by sort order, then code.">
            <Input aria-label="Sort order" inputMode="numeric" value={form.sortOrder} onChange={(e) => change("sortOrder", e.target.value)} />
          </Field>
          <Field label="Colour" hint="Optional six-digit hex.">
            <Input aria-label="Zone colour" placeholder="#2F855A" value={form.color} onChange={(e) => change("color", e.target.value)} />
          </Field>
          <Field label="Zone state" hint="Deactivating requires every rack to be inactive first.">
            <Select label="Zone state" value={form.isActive} onChange={(value) => change("isActive", value)} options={ACTIVE_OPTIONS} />
          </Field>
        </div>
        <Field label="Description" hint="Optional, up to 1000 characters.">
          <Input aria-label="Zone description" value={form.description} onChange={(e) => change("description", e.target.value)} />
        </Field>
      </Form>
    </Dialog>
  );
}

/* ------------------------------- Rack ------------------------------- */
export function RackDialog({ facilityId, zones, rack, onClose, onSaved }) {
  const editing = Boolean(rack);
  const [form, setForm] = useState({
    zoneId: rack?.zoneId || zones[0]?.id || "",
    aisleCode: rack?.aisleCode || "",
    rackCode: rack?.rackCode || "",
    widthM: String(rack?.dimensions?.widthM ?? 2),
    depthM: String(rack?.dimensions?.depthM ?? 0.6),
    heightM: String(rack?.dimensions?.heightM ?? 2),
    levelCount: String(rack?.levelCount ?? 4),
    cellsPerLevel: String(rack?.cellsPerLevel ?? 4),
    maxWeightKgPerLevel: String(rack?.maxWeightKgPerLevel ?? 500),
    mapX: String(rack?.mapX ?? 0),
    mapY: String(rack?.mapY ?? 0),
    orientation: String(rack?.orientation ?? 0),
    operationalStatus: rack?.operationalStatus || "AVAILABLE",
  });
  const [pending, setPending] = useState(false);
  const [error, setError] = useState("");
  const change = (key, value) => setForm((f) => ({ ...f, [key]: value }));

  async function submit(event) {
    event.preventDefault();
    if (pending) return;
    setError("");
    const code = (value) => value.trim().toUpperCase();
    if (!filled(form.aisleCode) || !CODE_PATTERN.test(code(form.aisleCode))) {
      setError("Aisle code must start with a letter or digit and use letters, digits, underscore or hyphen only.");
      return;
    }
    if (!editing && (!filled(form.rackCode) || !CODE_PATTERN.test(code(form.rackCode)))) {
      setError("Rack code must start with a letter or digit and use letters, digits, underscore or hyphen only.");
      return;
    }
    for (const [label, value] of [["width", form.widthM], ["depth", form.depthM], ["height", form.heightM]]) {
      if (!isPositive(value)) return setError(`Rack ${label} must be a positive number of metres.`);
    }
    if (!isInteger(form.mapX, 0, 100000) || !isInteger(form.mapY, 0, 100000)) {
      setError("Map X and Y must be whole numbers from 0 to 100000.");
      return;
    }
    if (!isPositive(form.maxWeightKgPerLevel, 1000000)) {
      setError("Level capacity must be a positive weight in kilograms.");
      return;
    }
    const dimensions = { widthM: number(form.widthM), depthM: number(form.depthM), heightM: number(form.heightM) };
    let levelCount;
    let cellsPerLevel;
    if (!editing) {
      if (!form.zoneId) {
        setError("Select the zone that owns this rack.");
        return;
      }
      if (!isInteger(form.levelCount, 1, 20) || !isInteger(form.cellsPerLevel, 1, 20)) {
        setError("Levels and cells per level must be whole numbers from 1 to 20.");
        return;
      }
      levelCount = number(form.levelCount);
      cellsPerLevel = number(form.cellsPerLevel);
      if (dimensions.widthM / cellsPerLevel <= 0) {
        setError("Rack width is too small for the requested cell layout.");
        return;
      }
    }
    setPending(true);
    try {
      const body = {
        aisleCode: code(form.aisleCode),
        dimensions,
        maxWeightKgPerLevel: number(form.maxWeightKgPerLevel),
        mapX: number(form.mapX),
        mapY: number(form.mapY),
        orientation: number(form.orientation),
        operationalStatus: form.operationalStatus,
      };
      if (editing) {
        await bomWarehouseApi.updateRack(rack.id, body);
      } else {
        const cellCapacity = floor2(number(form.maxWeightKgPerLevel) / cellsPerLevel);
        if (cellCapacity <= 0) {
          setError("Level capacity is too small to divide across the requested cells.");
          return;
        }
        await bomWarehouseApi.createRack({
          ...body,
          facilityId,
          zoneId: form.zoneId,
          rackCode: code(form.rackCode),
          levelCount,
          cellsPerLevel,
          cellCapacitiesKg: Array.from({ length: levelCount }, () => Array(cellsPerLevel).fill(cellCapacity)),
        });
      }
      onSaved?.();
      onClose?.();
    } catch (err) {
      setError(apiErrorMessage(err));
    } finally {
      setPending(false);
    }
  }

  return (
    <Dialog title={editing ? `Edit rack ${rack.rackCode}` : "Create rack"} onClose={onClose}>
      <Form pending={pending} error={error} onClose={onClose} onSubmit={submit} submitLabel={editing ? "Save rack" : "Create rack"}>
        <div className="manager-filters">
          {!editing && (
            <>
              <Field label="Zone">
                <Select
                  label="Rack zone"
                  value={form.zoneId}
                  onChange={(value) => change("zoneId", value)}
                  options={zones.map((z) => [z.id, `${z.code} · ${z.name}`])}
                />
              </Field>
              <Field label="Rack code" hint="Unique per facility.">
                <Input aria-label="Rack code" required value={form.rackCode} onChange={(e) => change("rackCode", e.target.value)} />
              </Field>
            </>
          )}
          <Field label="Aisle code">
            <Input aria-label="Aisle code" required value={form.aisleCode} onChange={(e) => change("aisleCode", e.target.value)} />
          </Field>
          <Field label="Operational status">
            <Select label="Rack status" value={form.operationalStatus} onChange={(value) => change("operationalStatus", value)} options={OPERATIONAL_STATUSES} />
          </Field>
          <Field label="Orientation">
            <Select label="Rack orientation" value={form.orientation} onChange={(value) => change("orientation", value)} options={ORIENTATIONS} />
          </Field>
          <Field label="Width (m)">
            <Input aria-label="Rack width in metres" inputMode="decimal" required value={form.widthM} onChange={(e) => change("widthM", e.target.value)} />
          </Field>
          <Field label="Depth (m)">
            <Input aria-label="Rack depth in metres" inputMode="decimal" required value={form.depthM} onChange={(e) => change("depthM", e.target.value)} />
          </Field>
          <Field label="Height (m)">
            <Input aria-label="Rack height in metres" inputMode="decimal" required value={form.heightM} onChange={(e) => change("heightM", e.target.value)} />
          </Field>
          <Field label="Level capacity (kg)" hint="Rated weight per level.">
            <Input aria-label="Level weight capacity" inputMode="decimal" required value={form.maxWeightKgPerLevel} onChange={(e) => change("maxWeightKgPerLevel", e.target.value)} />
          </Field>
          {!editing && (
            <>
              <Field label="Levels">
                <Input aria-label="Level count" inputMode="numeric" required value={form.levelCount} onChange={(e) => change("levelCount", e.target.value)} />
              </Field>
              <Field label="Cells per level" hint="Cells are generated automatically for each level.">
                <Input aria-label="Cells per level" inputMode="numeric" required value={form.cellsPerLevel} onChange={(e) => change("cellsPerLevel", e.target.value)} />
              </Field>
            </>
          )}
          <Field label="Map X">
            <Input aria-label="Map X position" inputMode="numeric" required value={form.mapX} onChange={(e) => change("mapX", e.target.value)} />
          </Field>
          <Field label="Map Y">
            <Input aria-label="Map Y position" inputMode="numeric" required value={form.mapY} onChange={(e) => change("mapY", e.target.value)} />
          </Field>
        </div>
        <p className="bom-warning">
          {editing
            ? "Dimensions, level capacity and status changes are rejected while cells hold inventory, allocations or reserved bookings."
            : "Creating a rack also creates every cell for the requested layout. The level weight is split evenly across cells; tune an individual cell afterwards."}
        </p>
      </Form>
    </Dialog>
  );
}

/* ------------------------------- Cell ------------------------------- */
export function CellDialog({ cell, onClose, onSaved }) {
  const [form, setForm] = useState({
    maxWeightKg: String(cell.maxWeightKg ?? 0),
    usableHeightM: cell.dimensions?.usableHeightM === null || cell.dimensions?.usableHeightM === undefined
      ? ""
      : String(cell.dimensions.usableHeightM),
    operationalStatus: cell.operationalStatus || "AVAILABLE",
  });
  const [pending, setPending] = useState(false);
  const [error, setError] = useState("");
  const change = (key, value) => setForm((f) => ({ ...f, [key]: value }));

  async function submit(event) {
    event.preventDefault();
    if (pending) return;
    setError("");
    if (!isPositive(form.maxWeightKg, 1000000)) {
      setError("Cell capacity must be a positive weight in kilograms.");
      return;
    }
    if (filled(form.usableHeightM) && !isPositive(form.usableHeightM, 100)) {
      setError("Usable height must be a positive number of metres, at most 100.");
      return;
    }
    setPending(true);
    try {
      const body = { maxWeightKg: number(form.maxWeightKg), operationalStatus: form.operationalStatus };
      if (filled(form.usableHeightM)) body.dimensions = { usableHeightM: number(form.usableHeightM) };
      await bomWarehouseApi.updateCell(cell.id, body);
      onSaved?.();
      onClose?.();
    } catch (err) {
      setError(apiErrorMessage(err));
    } finally {
      setPending(false);
    }
  }

  return (
    <Dialog title={`Edit cell ${cell.code}`} onClose={onClose}>
      <Form pending={pending} error={error} onClose={onClose} onSubmit={submit} submitLabel="Save cell">
        <div className="manager-filters">
          <Field label="Max weight (kg)" hint="Cannot go below the weight already stored.">
            <Input aria-label="Cell max weight" inputMode="decimal" required value={form.maxWeightKg} onChange={(e) => change("maxWeightKg", e.target.value)} />
          </Field>
          <Field label="Usable height (m)" hint="Optional; drives the cell volume.">
            <Input aria-label="Cell usable height" inputMode="decimal" value={form.usableHeightM} onChange={(e) => change("usableHeightM", e.target.value)} />
          </Field>
          <Field label="Operational status" hint="Block or maintain a cell before deleting its rack.">
            <Select label="Cell status" value={form.operationalStatus} onChange={(value) => change("operationalStatus", value)} options={OPERATIONAL_STATUSES} />
          </Field>
        </div>
        <p className="bom-warning">
          Cell width and depth are derived from the rack, so only the usable height can be tuned here. Structural changes are
          rejected while the cell is reserved or occupied.
        </p>
      </Form>
    </Dialog>
  );
}
